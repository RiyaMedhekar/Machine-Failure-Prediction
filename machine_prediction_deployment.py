import streamlit as st
import pandas as pd
import joblib

model = joblib.load("machine_failure_prediction.pkl")

st.title("Machine Failure Predcition")

#INPUT FIELDS
tempMode = st.number_input("tempMode")
AQ = st.number_input("AQ")
USS = st.number_input("USS")
CS = st.number_input("CS")
VOC = st.number_input("VOC")
RP = st.number_input("RP")
IP = st.number_input("IP")
Temperature = st.number_input("Temperature")
fail = st.number_input("fail")

# Prediction button
if st.button("Predict Machine Failure"):

    # Create input DataFrame
    input_data = pd.DataFrame({
        "tempMode": [tempMode],
        "AQ": [AQ],
        "USS": [USS],
        "CS": [CS],
        "VOC": [VOC],
        "RP": [RP],
        "IP": [IP],
        "Temperature": [Temperature]
    })

    # Make prediction
    prediction = model.predict(input_data)[0]

    # Display result
    if prediction == 1:
        st.error("Machine Failure Predicted")
    else:
        st.success("No Machine Failure Predicted")